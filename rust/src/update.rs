/// Written into the release archive so the version travels with the bytes.
pub const MANIFEST_NAME: &str = "okf-release.json";

/// The archive's own record of what it is. Every field is optional because
/// the TS casts parsed JSON without checking it.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ReleaseManifest {
    pub version: Option<String>,
    pub built_at: Option<String>,
    /// Files the archive is expected to contain at its root.
    pub contains: Option<Vec<String>>,
}

impl ReleaseManifest {
    /// Read the manifest from parsed JSON, ignoring fields of the wrong type.
    pub fn from_json(value: &Value) -> Self {
        let text = |key: &str| value.get(key).and_then(Value::as_str).map(String::from);
        Self {
            version: text("version"),
            built_at: text("builtAt"),
            contains: value.get("contains").and_then(Value::as_array).map(|items| {
                items.iter().filter_map(|i| i.as_str().map(String::from)).collect()
            }),
        }
    }
}

/// Directories an update replaces wholesale.
///
/// An allowlist, not "everything in the archive": the install directory also
/// holds things the archive has no business overwriting: `node_modules`
/// (regenerated by `bun install`), `build/` (regenerated by the build
/// scripts), and anything the user happens to have put there.
pub const REPLACED_PATHS: [&str; 23] = [
    "src",
    "test",
    "docs",
    "templates",
    "scripts",
    "assets",
    "package.json",
    "bun.lock",
    "tsconfig.json",
    "tsconfig.view.json",
    "vite.config.ts",
    "README.md",
    "CHANGELOG.md",
    "LICENSE",
    "SETUP.bat",
    "SETUP.command",
    "UNINSTALL.bat",
    "UNINSTALL.command",
    "PierrotKnowledge2.bat",
    "PierrotKnowledge2",
    // Entry by entry, not `rust/`: rust/target is a developer's cargo cache,
    // gigabytes that no release owns and an update must not move.
    "rust/Cargo.toml",
    "rust/Cargo.lock",
    "rust/src",
];

/// Files that have to be executable to be usable, relative to the install root.
///
/// The release archive is built on Windows, which does not record Unix
/// permissions, so everything arrives 0644 and the launcher a user is told to
/// run is not runnable until something sets the bit back. Forward slashes on
/// purpose: `join` normalises them and ZIP entry names are forward-slash.
pub const EXECUTABLE_PATHS: [&str; 5] = [
    "PierrotKnowledge2",
    "SETUP.command",
    "UNINSTALL.command",
    "scripts/setup.sh",
    "scripts/uninstall.sh",
];

/// Restore the executable bit on the files that need one.
///
/// A no-op on Windows, where the concept does not exist. Missing files are
/// skipped rather than reported: the set spans releases, and an install that
/// predates `UNINSTALL.command` is still a valid install.
#[cfg(unix)]
pub fn restore_executable_bits(install_dir: &str) -> Vec<String> {
    use std::os::unix::fs::PermissionsExt;

    let mut restored = Vec::new();
    for rel in EXECUTABLE_PATHS {
        let path = nodepath::join(&[install_dir, rel]);
        let Ok(meta) = fs::metadata(&path) else { continue };
        // Mirror the read bits into execute, so a file readable by the group is
        // runnable by it: the same shape `chmod +x` produces.
        let mode = meta.permissions().mode() & 0o777;
        let next = mode | ((mode & 0o444) >> 2);
        if next == mode {
            continue;
        }
        if fs::set_permissions(&path, fs::Permissions::from_mode(next)).is_ok() {
            restored.push(rel.to_string());
        }
    }
    restored
}

#[cfg(not(unix))]
pub fn restore_executable_bits(_install_dir: &str) -> Vec<String> {
    Vec::new()
}

/// A compiled artefact an update has just made stale.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct StaleArtifact {
    pub path: String,
    pub rebuild: String,
}

/// Compiled artefacts that an update has just made stale.
///
/// `build/` is deliberately not replaced: it is regenerated locally and the
/// archive does not carry the binaries. The consequence defeats the update:
/// the launcher prefers `build/cli/okf(.exe)` and agent hosts spawn
/// `build/headless/okf-mcp(.exe)` by the path in their config, so both keep
/// running the previous release until rebuilt. Reported rather than deleted:
/// removing the headless binary would leave every agent config pointing at a
/// file that is not there.
pub fn stale_compiled_artifacts(install_dir: &str) -> Vec<StaleArtifact> {
    let exe = |name: &str| if cfg!(windows) { format!("{name}.exe") } else { name.to_string() };
    [
        (nodepath::join(&[install_dir, "build", "cli", &exe("okf")]), "bun run build:cli"),
        (
            nodepath::join(&[install_dir, "build", "headless", &exe("okf-mcp")]),
            "bun run build:headless",
        ),
    ]
    .into_iter()
    .filter(|(path, _)| fs::metadata(path).is_ok())
    .map(|(path, rebuild)| StaleArtifact { path, rebuild: rebuild.to_string() })
    .collect()
}

