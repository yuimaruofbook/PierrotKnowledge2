#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ReleaseAsset {
    pub name: Option<String>,
    pub size: Option<u64>,
    pub browser_download_url: Option<String>,
    pub digest: Option<String>,
}

impl ReleaseAsset {
    pub fn named(name: &str) -> Self {
        Self { name: Some(name.to_string()), ..Self::default() }
    }

    fn from_json(value: &Value) -> Self {
        Self {
            name: value.get("name").and_then(Value::as_str).map(String::from),
            size: value.get("size").and_then(Value::as_f64).map(|n| n as u64),
            browser_download_url: value
                .get("browser_download_url")
                .and_then(Value::as_str)
                .map(String::from),
            digest: value.get("digest").and_then(Value::as_str).map(String::from),
        }
    }
}

/// Choose which attachment to install.
///
/// A release can carry more than one (this project's carried both the old
/// 285 MB full archive and the 0.57 MB source archive), so "the first zip" is
/// not good enough. A name ending in a version is the one built by `bun run
/// release`, and only that one contains the manifest the update decision
/// needs. Highest version wins, so re-attaching a newer build to an old
/// release still does the right thing.
pub fn pick_asset(assets: &[ReleaseAsset]) -> Option<&ReleaseAsset> {
    let zip = js_regex(r"(?i)\.zip$");
    let versioned = js_regex(r"(?i)-(<D>+)\.(<D>+)\.(<D>+)\.zip$");

    let zips: Vec<&ReleaseAsset> = assets
        .iter()
        .filter(|a| zip.is_match(a.name.as_deref().unwrap_or("")))
        .collect();

    let number = |caps: &regex::Captures, i: usize| caps[i].parse::<f64>().unwrap_or(f64::INFINITY);
    let mut ranked: Vec<(&ReleaseAsset, [f64; 3])> = zips
        .iter()
        .filter_map(|a| {
            let caps = versioned.captures(a.name.as_deref().unwrap_or(""))?;
            Some((*a, [number(&caps, 1), number(&caps, 2), number(&caps, 3)]))
        })
        .collect();
    // Stable, descending by (major, minor, patch).
    ranked.sort_by(|(_, a), (_, b)| {
        for i in 0..3 {
            if let Some(ord) = b[i].partial_cmp(&a[i]) {
                if ord != std::cmp::Ordering::Equal {
                    return ord;
                }
            }
        }
        std::cmp::Ordering::Equal
    });

    ranked.first().map(|(a, _)| *a).or_else(|| zips.first().copied())
}

const GITHUB_API: &str = "https://api.github.com";

fn agent() -> ureq::Agent {
    // A 404 or 403 is an answer to read, not an exception.
    ureq::Agent::config_builder()
        .http_status_as_error(false)
        .build()
        .into()
}

/// Look up the newest published release.
///
/// `Ok(None)` is "GitHub answered, but not with a usable release" (the TS
/// `null`); `Err` is a transport failure, which the TS lets propagate.
pub fn fetch_latest_release(source: &GithubSource) -> Result<Option<ReleaseInfo>, String> {
    fetch_latest_release_from(GITHUB_API, source)
}

/// [`fetch_latest_release`] against another API root, for tests.
pub fn fetch_latest_release_from(api_base: &str, source: &GithubSource) -> Result<Option<ReleaseInfo>, String> {
    let url = format!("{api_base}/repos/{}/{}/releases/latest", source.owner, source.repo);
    let mut response = agent()
        .get(&url)
        .header("accept", "application/vnd.github+json")
        .header("x-github-api-version", "2022-11-28")
        .call()
        .map_err(|e| e.to_string())?;

    if !response.status().is_success() {
        return Ok(None);
    }

    let text = response.body_mut().read_to_string().map_err(|e| e.to_string())?;
    let body: Value = serde_json::from_str(&text).map_err(|e| e.to_string())?;

    let assets: Vec<ReleaseAsset> = body
        .get("assets")
        .and_then(Value::as_array)
        .map(|items| items.iter().map(ReleaseAsset::from_json).collect())
        .unwrap_or_default();
    let Some(asset) = pick_asset(&assets) else { return Ok(None) };
    let Some(asset_url) = asset.browser_download_url.clone().filter(|u| !u.is_empty()) else {
        return Ok(None);
    };

    let field = |key: &str| body.get(key).and_then(Value::as_str).map(String::from);
    let tag = field("tag_name").unwrap_or_default();
    Ok(Some(ReleaseInfo {
        name: field("name").unwrap_or_else(|| tag.clone()),
        tag,
        notes: field("body").unwrap_or_default(),
        html_url: field("html_url").unwrap_or_default(),
        published_at: field("published_at").unwrap_or_default(),
        // Filled in after the archive is downloaded; the API cannot know it.
        version: None,
        asset_name: asset.name.clone().unwrap_or_default(),
        asset_url,
        asset_size: asset.size.unwrap_or(0),
        digest: asset.digest.clone(),
    }))
}

/// Download to a file, hashing as it goes so nothing is read twice.
///
/// Written as it arrives rather than buffered: these archives are hundreds of
/// megabytes. Returns the lowercase hex SHA-256 and the byte count.
/// `on_progress` gets `(received, total)`, with `total` 0 when the server did
/// not say.
pub fn download_and_hash(
    url: &str,
    to: &str,
    mut on_progress: Option<&mut dyn FnMut(u64, u64)>,
) -> Result<(String, u64), String> {
    let mut response = agent().get(url).call().map_err(|e| e.to_string())?;
    let status = response.status();
    if !status.is_success() {
        return Err(format!("ダウンロードに失敗しました: HTTP {}", status.as_u16()));
    }

    let total = response
        .headers()
        .get("content-length")
        .and_then(|v| v.to_str().ok())
        .and_then(|v| v.parse::<u64>().ok())
        .unwrap_or(0);

    let mut file = fs::File::create(to).map_err(|e| fsx_error(&e, "open", to))?;
    let mut hasher = Sha256::new();
    let mut received = 0u64;
    let mut reader = response.body_mut().with_config().limit(u64::MAX).reader();
    let mut buffer = vec![0u8; 64 * 1024];
    loop {
        let n = reader.read(&mut buffer).map_err(|e| e.to_string())?;
        if n == 0 {
            break;
        }
        hasher.update(&buffer[..n]);
        file.write_all(&buffer[..n]).map_err(|e| e.to_string())?;
        received += n as u64;
        if let Some(cb) = on_progress.as_mut() {
            cb(received, total);
        }
    }
    file.flush().map_err(|e| e.to_string())?;

    let hex: String = hasher.finalize().iter().map(|b| format!("{b:02x}")).collect();
    Ok((hex, received))
}

fn fsx_error(e: &std::io::Error, syscall: &'static str, path: &str) -> String {
    let code = match e.kind() {
        std::io::ErrorKind::NotFound => "ENOENT",
        std::io::ErrorKind::PermissionDenied => "EACCES",
        std::io::ErrorKind::AlreadyExists => "EEXIST",
        _ => "EIO",
    };
    fsx::FsError { code, syscall, path: Some(path.to_string()), dest: None }.to_string()
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UpdatePlan {
    pub verdict: UpdateVerdict,
    /// `None` when the plan stopped before asking GitHub.
    pub release: Option<ReleaseInfo>,
    pub installed: InstalledInfo,
}

/// Where the application is installed.
#[derive(Debug, Clone, Default)]
pub struct FindInstallDirOptions {
    /// Where the running code lives, when that is inside the install tree
    /// (the TS `import.meta.dir`; a compiled binary has none).
    pub module_dir: Option<String>,
    pub exec_path: Option<String>,
    pub cwd: Option<String>,
}

/// Where the application is installed.
///
/// Not derivable from the module alone: compiled, the code's own path is not
/// the install tree, so resolving upwards from it lands in the wrong place.
/// Each plausible root is therefore tried and *verified* by looking for the
/// files that only this project's root has. A wrong guess here would have the
/// updater replace the wrong directory.
pub fn find_install_dir(options: &FindInstallDirOptions) -> Option<String> {
    let exec_path = options
        .exec_path
        .clone()
        .or_else(|| std::env::current_exe().ok().map(|p| p.to_string_lossy().into_owned()))
        .unwrap_or_default();
    let cwd = options
        .cwd
        .clone()
        .or_else(|| std::env::current_dir().ok().map(|p| p.to_string_lossy().into_owned()))
        .unwrap_or_default();

    let mut parts: Vec<&str> = exec_path.split(['/', '\\']).collect();
    parts.pop();
    let exec_dir = parts.join("/");

    let mut candidates: Vec<String> = Vec::new();
    // Running from source: src/bun/ -> root.
    if let Some(module_dir) = &options.module_dir {
        candidates.push(nodepath::resolve(&[module_dir, "../.."]));
    }
    // Compiled to build/cli/okf.exe -> root.
    candidates.push(nodepath::resolve(&[&exec_dir, "../.."]));
    // Started from the project directory.
    candidates.push(nodepath::resolve1(&cwd));
    candidates.push(nodepath::resolve(&[&cwd, ".."]));

    candidates.into_iter().find(|c| looks_like_install(c))
}

/// A root has our package.json and the source tree beside it.
fn looks_like_install(dir: &str) -> bool {
    let Ok(text) = fsx::read_text(&nodepath::join(&[dir, "package.json"])) else {
        return false;
    };
    let Ok(pkg) = serde_json::from_str::<Value>(&text) else {
        return false;
    };
    let named = match pkg.get("name") {
        Some(Value::String(s)) => !s.is_empty(),
        Some(Value::Null) | Some(Value::Bool(false)) | None => false,
        Some(Value::Number(n)) => n.as_f64().is_some_and(|x| x != 0.0),
        Some(_) => true,
    };
    named && fs::read_dir(nodepath::join(&[dir, "src"])).is_ok()
}

/// Read the installed version from `package.json` plus the update record.
pub fn read_installed(install_dir: &str) -> Result<InstalledInfo, String> {
    let text = fsx::read_text(&nodepath::join(&[install_dir, "package.json"])).map_err(|e| e.to_string())?;
    let pkg: Value = serde_json::from_str(&text).map_err(|e| e.to_string())?;

    // No record: this install predates the updater, which is fine.
    let record: Value = fsx::read_text(&nodepath::join(&[install_dir, MANIFEST_NAME]))
        .ok()
        .and_then(|t| serde_json::from_str(&t).ok())
        .unwrap_or(Value::Null);

    let text_of = |v: &Value, key: &str| v.get(key).and_then(Value::as_str).map(String::from);
    let version = text_of(&record, "version")
        .or_else(|| text_of(&pkg, "version"))
        .unwrap_or_else(|| "0.0.0".to_string());

    Ok(InstalledInfo {
        version,
        tag: text_of(&record, "tag").filter(|t| !t.is_empty()),
        published_at: text_of(&record, "publishedAt").filter(|t| !t.is_empty()),
    })
}

/// Everything that can be decided before downloading 285 MB.
///
/// `release_version` comes from the caller because only the archive knows it,
/// and reading the archive means fetching it. Callers that have not fetched
/// yet pass `None` and get told to look.
pub fn plan_update(
    install_dir: &str,
    known_bundles: &[&str],
    source: Option<&GithubSource>,
    release_version: Option<&str>,
) -> Result<UpdatePlan, String> {
    plan_update_from(GITHUB_API, install_dir, known_bundles, source, release_version)
}

/// [`plan_update`] against another API root, for tests.
pub fn plan_update_from(
    api_base: &str,
    install_dir: &str,
    known_bundles: &[&str],
    source: Option<&GithubSource>,
    release_version: Option<&str>,
) -> Result<UpdatePlan, String> {
    let installed = read_installed(install_dir)?;

    let safety = check_safe_to_update(install_dir, known_bundles);
    if !safety.ok {
        return Ok(UpdatePlan {
            verdict: UpdateVerdict::Refuse { reason: safety.problems.join("\n") },
            release: None,
            installed,
        });
    }

    let default_source = GithubSource::default_source();
    let Some(mut release) = fetch_latest_release_from(api_base, source.unwrap_or(&default_source))? else {
        return Ok(UpdatePlan {
            verdict: UpdateVerdict::Refuse { reason: "リリース情報を取得できませんでした。".to_string() },
            release: None,
            installed,
        });
    };

    release.version = release_version.map(String::from);
    let verdict = decide_update(&installed, &release);
    Ok(UpdatePlan { verdict, release: Some(release), installed })
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ApplyResult {
    pub backup_dir: String,
    pub replaced: Vec<String>,
}

fn exists(path: &str) -> bool {
    fs::metadata(path).is_ok()
}

/// `cp(from, to, { recursive: true })`.
fn copy_recursive(from: &Path, to: &Path) -> std::io::Result<()> {
    if from.is_dir() {
        fs::create_dir_all(to)?;
        for entry in fs::read_dir(from)? {
            let entry = entry?;
            copy_recursive(&entry.path(), &to.join(entry.file_name()))?;
        }
        Ok(())
    } else {
        fs::copy(from, to).map(|_| ())
    }
}

fn remove_all(path: &str) {
    let p = Path::new(path);
    let _ = if p.is_dir() && !fs::symlink_metadata(p).is_ok_and(|m| m.file_type().is_symlink()) {
        fs::remove_dir_all(p)
    } else {
        fs::remove_file(p)
    };
}

/// Swap an extracted tree into place, keeping the old one.
///
/// Nothing is deleted. The previous copy of each replaced path is moved into a
/// timestamped backup directory, so a bad release is undone by moving them
/// back, which [`rollback`] does. `staged_root` is the directory holding
/// `src/`, `package.json` and so on; `backup_root` overrides the default
/// `<install>/.okf-backup/<stamp>`.
pub fn apply_update(install_dir: &str, staged_root: &str, backup_root: Option<&str>) -> Result<ApplyResult, String> {
    let stamp = fsx::now_iso().replace([':', '.'], "-");
    let backup_dir = match backup_root {
        Some(dir) => dir.to_string(),
        None => nodepath::join(&[install_dir, ".okf-backup", &stamp]),
    };
    fsx::mkdir_p(&backup_dir).map_err(|e| e.to_string())?;

    let mut replaced: Vec<String> = Vec::new();
    let mut done: Vec<(String, String)> = Vec::new();
    // Every path this wrote, whether or not something was there before. The
    // undo has to remove these as well: a newly added top-level file has no
    // backup to restore over it.
    let mut created: Vec<String> = Vec::new();

    let attempt = (|| -> Result<(), String> {
        for name in REPLACED_PATHS {
            let incoming = nodepath::join(&[staged_root, name]);
            if !exists(&incoming) {
                continue;
            }

            let current = nodepath::join(&[install_dir, name]);
            if exists(&current) {
                // A nested entry (rust/src) needs its parent in the backup too.
                let parked = nodepath::join(&[&backup_dir, name]);
                fs::create_dir_all(nodepath::dirname(&parked)).map_err(|e| fsx_error(&e, "mkdir", &parked))?;
                fsx::rename(&current, &parked).map_err(|e| e.to_string())?;
                done.push((name.to_string(), current.clone()));
            }

            fs::create_dir_all(nodepath::dirname(&current)).map_err(|e| fsx_error(&e, "mkdir", &current))?;
            copy_recursive(Path::new(&incoming), Path::new(&current))
                .map_err(|e| fsx_error(&e, "cp", &incoming))?;
            created.push(current);
            replaced.push(name.to_string());
        }

        // The archive carries no Unix permissions, so the launcher we just
        // replaced is 0644 and the user's next `./PierrotKnowledge2` is
        // "Permission denied": an update that appears to have broken the app.
        restore_executable_bits(install_dir);
        Ok(())
    })();

    if let Err(error) = attempt {
        // Put back whatever was moved before the failure, so a half-applied
        // update never survives. Anything this run created is removed first,
        // including the paths that had no previous version to restore over.
        for path in created.iter().rev() {
            remove_all(path);
        }
        for (name, from) in done.iter().rev() {
            let _ = fs::rename(nodepath::join(&[&backup_dir, name]), from);
        }
        return Err(error);
    }

    Ok(ApplyResult { backup_dir, replaced })
}

/// Undo an [`apply_update`] from its backup directory.
pub fn rollback(install_dir: &str, backup_dir: &str) -> Result<Vec<String>, String> {
    let mut restored = Vec::new();
    for name in fsx::read_dir_names(backup_dir).map_err(|e| e.to_string())? {
        // `rust` in the backup holds only rust/src and the manifests. Restoring
        // the folder whole would delete rust/target, which no update touched.
        let prefix = format!("{name}/");
        let nested: Vec<String> = REPLACED_PATHS
            .iter()
            .filter(|path| path.starts_with(&prefix))
            .map(|path| path.to_string())
            .collect();
        let entries = if nested.is_empty() { vec![name] } else { nested };

        for entry in entries {
            let from = nodepath::join(&[backup_dir, &entry]);
            if !exists(&from) {
                continue;
            }
            let target = nodepath::join(&[install_dir, &entry]);
            remove_all(&target);
            fs::create_dir_all(nodepath::dirname(&target)).map_err(|e| fsx_error(&e, "mkdir", &target))?;
            fsx::rename(&from, &target).map_err(|e| e.to_string())?;
            restored.push(entry);
        }
    }
    Ok(restored)
}

/// Record what was installed, so the next check has something to compare.
pub fn write_install_record(install_dir: &str, info: &InstalledInfo) -> Result<(), String> {
    let text = serde_json::to_string_pretty(info).map_err(|e| e.to_string())?;
    fsx::write_text(&nodepath::join(&[install_dir, MANIFEST_NAME]), &format!("{text}\n"))
        .map_err(|e| e.to_string())
}

/// Verify a download against the digest GitHub reported.
pub fn digest_matches(expected: Option<&str>, actual: &str) -> bool {
    sha256_from_digest(expected).is_some_and(|want| want == actual.to_lowercase())
}

/// `ReleaseManifest` is read from an archive; kept here so callers need one import.
pub fn parse_manifest(text: &str) -> Option<ReleaseManifest> {
    let value: Value = serde_json::from_str(js_trim(text).trim_start_matches('\u{feff}')).ok()?;
    Some(ReleaseManifest::from_json(&value))
}

