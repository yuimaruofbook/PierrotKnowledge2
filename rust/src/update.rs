//! Updating from a GitHub release (`src/bun/update.ts`).
//!
//! The releases for this project are archives uploaded by hand, which is a
//! perfectly good distribution channel: GitHub computes a SHA-256 for every
//! asset server-side and reports it on the API, so the download can be
//! verified against something the uploader did not control.
//!
//! The order of operations is the safety:
//!
//! 1. Ask GitHub what is published, and refuse anything without a digest.
//! 2. Refuse to go backwards (see [`decide_update`]).
//! 3. Refuse outright if a knowledge bundle sits inside the install directory,
//!    because there an update *is* a deletion.
//! 4. Download to a staging directory and hash it. A mismatch stops here,
//!    before anything on disk has been touched.
//! 5. Move the current files aside into a timestamped backup (never delete),
//!    then put the new ones in.
//! 6. On any failure after step 5, put the backup back.
//!
//! What is never touched, by construction: the bundle (it lives outside the
//! install directory, and step 3 proves it), and the app-data folder.
//!
//! Unlike the TypeScript these functions are blocking; the CLI has nothing
//! else to do while they run.

